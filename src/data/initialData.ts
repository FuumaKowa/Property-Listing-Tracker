export function parseUnitsInfo(unitsStr: string): {
  available: number | null;
  total: number | null;
  percentage: number | null;
  displayType: 'ratio' | 'count' | 'percentage' | 'soldOut' | 'other';
} {
  const clean = (unitsStr || '').trim();
  if (!clean || clean === '0' || clean.startsWith('0/')) {
    const totalMatch = clean.match(/^0\/(\d+)$/);
    const total = totalMatch ? parseInt(totalMatch[1], 10) : null;
    return { available: 0, total, percentage: 0, displayType: 'soldOut' };
  }

  // Ratio format: 10/62
  const ratioMatch = clean.match(/^(\d+)\s*\/\s*(\d+)$/);
  if (ratioMatch) {
    const available = parseInt(ratioMatch[1], 10);
    const total = parseInt(ratioMatch[2], 10);
    const percentage = total > 0 ? Math.round((available / total) * 100) : 0;
    return { available, total, percentage, displayType: 'ratio' };
  }

  // Percentage format: 70% Booking or 70%
  const pctMatch = clean.match(/^(\d+(?:\.\d+)?)\s*%/);
  if (pctMatch) {
    const percentage = parseFloat(pctMatch[1]);
    return { available: null, total: null, percentage, displayType: 'percentage' };
  }

  // Count format: 784 or 3
  const countMatch = clean.match(/^(\d+)$/);
  if (countMatch) {
    const available = parseInt(countMatch[1], 10);
    return { available, total: null, percentage: null, displayType: 'count' };
  }

  return { available: null, total: null, percentage: null, displayType: 'other' };
}
