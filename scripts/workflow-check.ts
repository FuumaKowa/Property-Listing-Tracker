import assert from 'node:assert/strict';
import {applyWorkflowAction, ownerReport, workflowStage, parseBrief,needsWorkflowReview} from '../src/workflow/model';
import {previewUsers, seedWorkflow} from '../src/workflow/seed';

const person=(id:number)=>({actual:previewUsers[0],effective:previewUsers.find(u=>u.id===id)!});
let w=seedWorkflow()[0];
const act=(id:number,action:any)=>{w=applyWorkflowAction(w,action,person(id));};
assert.throws(()=>act(5,{type:'handoff'}),/permission|Eypa|coordinator/i);
act(2,{type:'handoff'});
assert.equal(workflowStage(w),'Production');
act(3,{type:'addMaterial',kind:'copy',title:'Sale caption',text:'Verified sample copy'});
const copy=w.materials.at(-1)!.id;
act(3,{type:'addMaterial',kind:'photo',title:'Prepared photo',fileKey:'photo.png',mime:'image/png'});
const photo=w.materials.at(-1)!.id;
act(3,{type:'addMaterial',kind:'video',title:'Video draft',fileKey:'video.mp4',mime:'video/mp4'});
const video=w.materials.at(-1)!.id;
act(3,{type:'submit',ids:[photo,copy,video]});
assert.equal(workflowStage(w),'Review');
assert.throws(()=>act(5,{type:'review',ids:[photo],approved:true}),/permission|reviewer/i);
act(4,{type:'review',ids:[photo,copy],approved:true});
act(4,{type:'addDestination',channelId:'facebook-page'});
act(4,{type:'addDestination',channelId:'tiktok'});
assert.throws(()=>act(4,{type:'approveDestination',channelId:'tiktok',materialIds:[copy,video]}),/approved/i);
act(4,{type:'approveDestination',channelId:'facebook-page',materialIds:[photo,copy]});
assert.equal(workflowStage(w),'Publishing');
assert.throws(()=>act(3,{type:'publish',channelId:'facebook-page',url:'https://example.com/ad'}),/permission|publisher/i);
act(5,{type:'publish',channelId:'facebook-page',url:'https://example.com/ad'});
assert.match(ownerReport(w),/Interim/i);
assert.match(ownerReport(w),/Facebook Page Rumahlot : https:\/\/example.com\/ad/);
assert.match(ownerReport(w),/TikTok : Pending approval/);
act(2,{type:'sent'});
assert.notEqual(workflowStage(w),'Owner informed');
assert.equal(w.events[0].actualName,'Daniel');
assert.equal(w.events[0].effectiveName,'Eypa');
act(4,{type:'review',ids:[video],approved:true});
act(4,{type:'approveDestination',channelId:'tiktok',materialIds:[copy,video]});
act(5,{type:'publish',channelId:'tiktok',url:'https://example.com/video'});
assert.equal(workflowStage(w),'Owner update');
act(2,{type:'sent'});
assert.equal(workflowStage(w),'Owner informed');
act(3,{type:'addMaterial',kind:'copy',title:'Revised caption',text:'New verified price',replacesId:copy});
assert.equal(w.destinations[0].approval,null);
assert.equal(w.destinations[0].publications[0].url,'https://example.com/ad');
assert.notEqual(workflowStage(w),'Owner informed');
assert.throws(()=>act(5,{type:'publish',channelId:'facebook-page',url:'https://example.com/revised'}),/approval/i);
const newCopy=w.materials.at(-1)!.id;
act(3,{type:'submit',ids:[newCopy]});
act(4,{type:'review',ids:[newCopy],approved:false,note:'Confirm the price first'});
assert.equal(w.materials.at(-1)!.review,'changes');
assert.throws(()=>act(4,{type:'review',ids:[newCopy],approved:true}),/submitted/i);
act(2,{type:'saveBrief',brief:{...w.brief,permission:false}});
assert.equal(workflowStage(w),'On hold');
assert.throws(()=>act(4,{type:'approveDestination',channelId:'facebook-page',materialIds:[photo,copy]}),/permission/i);

const brief=parseBrief('REF: WTS-202610-00019\n* Property: Tanah Sawit\n* Location: Sungai Besar, Selangor\n* Contact Name: Suraya\n* Contact: 016-907 1619\n* WhatsApp: https://wa.me/60169071619\n🔗 ORIGINAL LISTING\nhttps://www.mudah.my/tanah-sawit-115902351.htm\n📌 TASK\n* Confirm actual asking price with owner\n📌 STATUS\n* Owner Appointment: APPROVED');
assert.equal(brief.property,'Tanah Sawit');
assert.equal(brief.ownerName,'Suraya');
assert.equal(brief.sourceUrl,'https://www.mudah.my/tanah-sawit-115902351.htm');
assert.equal(brief.permission,false,'Pasted approval must be confirmed explicitly');
assert.equal(brief.tasks.length,1);
let reviewed=seedWorkflow()[0];
for(const action of [{type:'handoff'},{type:'addMaterial',kind:'copy',title:'Caption',text:'Sample'}] as any[])reviewed=applyWorkflowAction(reviewed,action,person(1));
reviewed=applyWorkflowAction(reviewed,{type:'submit',ids:[reviewed.materials[0].id]},person(3));
reviewed=applyWorkflowAction(reviewed,{type:'review',ids:[reviewed.materials[0].id],approved:true},person(4));
assert.equal(workflowStage(reviewed),'Review','Dr Shahril still needs to select publishing destinations after approving materials');
assert.equal(needsWorkflowReview(reviewed),true,'Destination selection stays in the review queue');
assert.equal(needsWorkflowReview(seedWorkflow()[1]),true,'Ready platform approval is included in the review queue');
