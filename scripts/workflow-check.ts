import assert from 'node:assert/strict';
import {applyWorkflowAction,ownerReport,workflowStage,needsWorkflowReview,parseBrief} from '../src/workflow/model';
import {previewUsers,seedWorkflow} from '../src/workflow/seed';
const context=(id:number)=>({actual:previewUsers[0],effective:previewUsers.find(u=>u.id===id)!});
let w=seedWorkflow()[0];
const act=(id:number,action:any)=>{w=applyWorkflowAction(w,action,context(id));};
assert.throws(()=>act(5,{type:'handoff'}),/permission|coordinator/i);
act(2,{type:'handoff'});
act(3,{type:'addMaterial',kind:'copy',title:'Verified caption',text:'Verified listing copy'});
act(3,{type:'addMaterial',kind:'photo',title:'Prepared photo',fileKey:'photo.png',mime:'image/png'});
const [copy,photo]=w.materials.map(m=>m.id);
act(3,{type:'submit',ids:[copy,photo]});
assert.deepEqual(w.materials.map(m=>m.review),['approved','approved']);
assert.equal(needsWorkflowReview(w),false);
assert.equal(workflowStage(w),'Publishing');
assert.throws(()=>act(4,{type:'approveForPublishing',channelIds:['facebook-page'],materialIds:[copy,photo]}),/permission|publisher/i);
act(5,{type:'approveForPublishing',channelIds:['facebook-page','tiktok'],materialIds:[copy,photo]});
assert.ok(w.destinations.find(d=>d.channelId==='facebook-page')!.approval);
assert.equal(w.destinations.find(d=>d.channelId==='tiktok')!.approval,null);
assert.match(ownerReport(w),/TikTok : Pending materials/);
act(5,{type:'publish',channelId:'facebook-page',url:'https://example.com/ad'});
act(2,{type:'sent'});
assert.equal(w.events[0].effectiveName,'Eypa');
act(3,{type:'addMaterial',kind:'copy',title:'Revised caption',text:'Updated verified copy',replacesId:copy});
assert.equal(w.destinations.find(d=>d.channelId==='facebook-page')!.approval,null);
assert.equal(w.destinations.find(d=>d.channelId==='facebook-page')!.publications[0].url,'https://example.com/ad');
assert.notEqual(workflowStage(w),'Owner informed');
const pending=w.materials.at(-1)!.id;act(3,{type:'submit',ids:[pending]});
assert.equal(w.materials.at(-1)!.review,'approved');
act(5,{type:'approveForPublishing',channelIds:['facebook-page','tiktok'],materialIds:[pending,photo]});
assert.match(ownerReport(w),/Facebook Page Rumahlot : Pending publication/);
act(2,{type:'saveBrief',brief:{...w.brief,permission:false}});
assert.equal(workflowStage(w),'On hold');
assert.throws(()=>act(5,{type:'publish',channelId:'tiktok',url:'https://example.com/video'}),/permission/i);
const brief=parseBrief('REF: WTS-202610-00019\n* Property: Tanah Sawit\n* Location: Sungai Besar, Selangor\n* Contact Name: Suraya\n* Contact: 016-907 1619\n* WhatsApp: https://wa.me/60169071619\n🔗 ORIGINAL LISTING\nhttps://www.mudah.my/tanah-sawit-115902351.htm\n📌 TASK\n* Confirm actual asking price with owner\n📌 STATUS\n* Owner Appointment: APPROVED');
assert.equal(brief.property,'Tanah Sawit');assert.equal(brief.ownerName,'Suraya');assert.equal(brief.sourceUrl,'https://www.mudah.my/tanah-sawit-115902351.htm');assert.equal(brief.permission,false);assert.equal(brief.tasks.length,1);
console.log('PASS workflow handoff, automatic material release, Muz selection, publication history, owner permission and brief parsing');
