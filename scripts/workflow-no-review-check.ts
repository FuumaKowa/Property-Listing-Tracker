import assert from 'node:assert/strict';
import {applyWorkflowAction,workflowStage,needsWorkflowReview,ownerReport} from '../src/workflow/model';
import {previewUsers,seedWorkflow} from '../src/workflow/seed';
const user=(id:number)=>({actual:previewUsers[0],effective:previewUsers.find(u=>u.id===id)!});
let w=seedWorkflow()[0];
const act=(id:number,action:any)=>{w=applyWorkflowAction(w,action,user(id));};
act(2,{type:'handoff'});
act(3,{type:'addMaterial',kind:'copy',title:'Verified caption',text:'Verified sample listing copy'});
act(3,{type:'addMaterial',kind:'photo',title:'Prepared photo',fileKey:'photo.png',mime:'image/png'});
const [copy,photo]=w.materials.map(m=>m.id);
act(3,{type:'submit',ids:[copy,photo]});
assert.equal(w.materials.every(m=>m.review==='approved'),true,'submitted materials are released automatically to Muz');
assert.equal(needsWorkflowReview(w),false,'reviewer never appears as a workflow gate');
assert.equal(workflowStage(w),'Publishing','complete prepared materials move directly to Muz');
assert.throws(()=>act(4,{type:'approveForPublishing',channelIds:['facebook-page'],materialIds:[copy,photo]}),/permission|publisher/i,'Dr Shahril cannot hold or approve the handoff');
act(5,{type:'approveForPublishing',channelIds:['facebook-page','tiktok'],materialIds:[copy,photo]});
assert.ok(w.destinations.find(d=>d.channelId==='facebook-page')?.approval,'Muz can choose a ready photo platform');
assert.equal(w.destinations.find(d=>d.channelId==='tiktok')?.approval,null,'Muz can see a selected video platform waiting for video');
assert.match(ownerReport(w),/TikTok : Pending materials/);
act(3,{type:'addMaterial',kind:'video',title:'Prepared video',fileKey:'video.mp4',mime:'video/mp4'});
const video=w.materials.at(-1)!.id;
act(3,{type:'submit',ids:[video]});
act(5,{type:'approveForPublishing',channelIds:['facebook-page','tiktok'],materialIds:[copy,photo,video]});
assert.ok(w.destinations.find(d=>d.channelId==='tiktok')?.approval,'TikTok becomes ready after video is submitted');
act(5,{type:'publish',channelId:'facebook-page',url:'https://example.com/ad'});
assert.match(ownerReport(w),/Facebook Page Rumahlot : https:\/\/example.com\/ad/);
act(2,{type:'saveBrief',brief:{...w.brief,permission:false}});
assert.equal(workflowStage(w),'On hold','owner permission still pauses publishing');
assert.throws(()=>act(5,{type:'publish',channelId:'tiktok',url:'https://example.com/video'}),/permission/i);
let automatic=seedWorkflow()[0];
automatic=applyWorkflowAction(automatic,{type:'handoff'},user(2));
automatic=applyWorkflowAction(automatic,{type:'addMaterial',kind:'photo',title:'Original',fileKey:'original.png',mime:'image/png',original:true},user(3));
automatic=applyWorkflowAction(automatic,{type:'startProduction',provider:'template'},user(2));
assert.deepEqual(automatic.production?.channelIds,[],'automatic production must leave platform selection to Muz');
console.log('PASS direct-to-Muz handoff, producer auto-release, Muz destination choice, partial video readiness, reports and owner permission');
