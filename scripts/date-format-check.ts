import assert from 'node:assert/strict';
import { existsSync } from 'node:fs';
assert.ok(existsSync('src/utils/datePresentation.ts'), 'Shared day-first date formatting must exist');
const { formatCalendarDate, formatDateTime, dateInputValue, normalizeDateEdit, formatAuditValue } = await import('../src/utils/datePresentation');
assert.equal(formatCalendarDate('2026-09-30'),'30/09/2026');
assert.equal(formatCalendarDate('05/10/2026'),'05/10/2026','Day/month order must not be reversed');
assert.equal(formatCalendarDate('2026-01-01'),'01/01/2026','Calendar dates must not shift with timezone');
assert.equal(formatCalendarDate('23.10'),'23/10 (year not recorded)','Do not invent missing years');
assert.equal(formatCalendarDate('29.2.2024'),'29/02/2024');
assert.equal(formatCalendarDate('31/02/2026'),'31/02/2026','Invalid legacy dates remain visible without reinterpretation');
assert.equal(formatCalendarDate(null,'Not scheduled'),'Not scheduled');
assert.equal(dateInputValue('2026-10-05'),'05/10/2026');
assert.equal(normalizeDateEdit('05/10/2026','2026-10-05'),'2026-10-05');
assert.equal(normalizeDateEdit('23/10','23.10'),'23.10','Saving other fields must preserve the original date');
assert.equal(normalizeDateEdit('05/10/2026','5.10.2026'),'5.10.2026','Unchanged display must preserve original stored spelling');
assert.equal(normalizeDateEdit('30/09/2026','23.10'),'2026-09-30');
assert.equal(normalizeDateEdit('29/02/2024'),'2024-02-29');
assert.equal(normalizeDateEdit(''),'');
assert.throws(()=>normalizeDateEdit('29/02/2026'));
assert.throws(()=>normalizeDateEdit('10/23/2026'));
assert.throws(()=>normalizeDateEdit('23/10'));
assert.throws(()=>normalizeDateEdit('2026-10-23'));
assert.throws(()=>normalizeDateEdit('01/01/0026'),'Do not expand a four-digit year as if it had two digits');
assert.throws(()=>normalizeDateEdit('01/01/0000'));
const timestamp = new Date(2026,8,30,16,5).toISOString();
assert.equal(formatDateTime(timestamp),'30/09/2026, 16:05');
assert.equal(formatDateTime('not a date'),'not a date');
assert.equal(formatAuditValue('property_guru_repost_date','2026-10-05'),'05/10/2026');
assert.equal(formatAuditValue('archived_at',timestamp),'30/09/2026, 16:05');
assert.equal(formatAuditValue('notes','2026-10-05'),'2026-10-05','Free text is not rewritten');
console.log('PASS day-first dates, local timestamps, leap years, strict inputs and unchanged legacy-date preservation');
