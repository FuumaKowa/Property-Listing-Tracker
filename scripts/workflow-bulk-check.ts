import assert from 'node:assert/strict';
import {applyWorkflowAction,workflowStage,currentPublication,ownerReport,type WorkflowListing} from '../src/workflow/model';
import {seedWorkflow,previewUsers} from '../src/workflow/seed';
const context=(id:number)=>({actual:previewUsers[0],effective:previewUsers.find(u=>u.id===id)!});
let w=seedWorkflow()[0];
const act=(id:number,action:any)=>{w=applyWorkflowAction(w,action,context(id));};
act(2,{type:'handoff'});
act(3,{type:'addMaterial',kind:'photo',title:'Reviewed photo',fileKey:'photo.png',mime:'image/png'});
act(3,{type:'addMaterial',kind:'copy',title:'Reviewed copy',text:'A verified sample caption.'});
act(3,{type:'addMaterial',kind:'video',title:'Pending video',fileKey:'video.mp4',mime:'video/mp4'});
const [photo,copy,video]=w.materials.map(m=>m.id);
act(3,{type:'submit',ids:[photo,copy,video]});
const channels=['facebook-page','telegram-subsale','whatsapp-nhc','tiktok'];
const approval={type:'approveForPublishing',channelIds:channels,materialIds:[photo,copy]};
assert.throws(()=>act(5,approval),/permission|reviewer/i);
const version=w.version;
act(4,approval);
assert.equal(w.version,version+1,'One atomic handoff');
assert.equal(workflowStage(w),'Publishing');
assert.equal(w.destinations.filter(d=>d.approval).length,3,'Photos and copy proceed to three destinations');
assert.equal(w.destinations.find(d=>d.channelId==='tiktok')!.approval,null,'Video destination remains pending');
assert.deepEqual(w.materials.map(m=>m.review),['approved','approved','submitted']);
assert.equal(w.events[0].effectiveName,'Dr Shahril');
assert.match(w.events[0].message,/3.*Muz/);
assert.match(ownerReport(w),/TikTok : Pending approval/);
assert.match(ownerReport(w),/Mudah : N\/A/);
assert.throws(()=>act(4,approval),/ready|already/i,'Retry cannot invalidate previous platform approvals');
const originalApproval=w.destinations[0].approval!.id;
act(5,{type:'publish',channelId:'facebook-page',url:'https://example.com/published'});
const originalPublication=currentPublication(w.destinations[0])!.id;
act(4,{type:'setDestinations',channelIds:['facebook-page','whatsapp-nhc','tiktok']});
assert.equal(w.destinations.some(d=>d.channelId==='telegram-subsale'),false,'Unticked unpublished destination is removed');
assert.throws(()=>act(4,{type:'setDestinations',channelIds:['tiktok']}),/published|history/i);
act(4,{type:'approveForPublishing',channelIds:['facebook-page','whatsapp-nhc','tiktok'],materialIds:[photo,copy,video]});
assert.equal(w.destinations[0].approval!.id,originalApproval,'Approving video later preserves the existing Facebook package');
assert.equal(currentPublication(w.destinations[0])!.id,originalPublication,'Published Facebook link stays complete');
assert.deepEqual(w.destinations.find(d=>d.channelId==='tiktok')!.approval!.materialIds,[copy,video]);

const before=structuredClone(w);
function rejected(action:any,pattern:RegExp){assert.throws(()=>applyWorkflowAction(w,action,context(4)),pattern);assert.deepEqual(w,before);}
rejected({type:'setDestinations',channelIds:['facebook-page','unknown']},/channel|destination/i);
rejected({type:'setDestinations',channelIds:['facebook-page','facebook-page']},/unique|duplicate/i);
rejected({type:'approveForPublishing',channelIds:['facebook-page','mudah'],materialIds:['bad-id']},/material/i);
const blocked:WorkflowListing={...w,brief:{...w.brief,tasks:[{id:'price',label:'Confirm price',done:false}]}};
assert.throws(()=>applyWorkflowAction(blocked,{type:'approveForPublishing',channelIds:[...channels,'mudah'],materialIds:[photo,copy]} as any,context(4)),/checks/i);
const withdrawn={...w,brief:{...w.brief,permission:false}};
assert.throws(()=>applyWorkflowAction(withdrawn,approval as any,context(4)),/permission/i);
console.log('PASS one-click partial handoff, bulk choices, permissions, atomic rejection and preservation of published packages');
