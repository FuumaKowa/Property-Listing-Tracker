import assert from 'node:assert/strict';
import {applyWorkflowAction,workflowStage,currentPublication,ownerReport,type WorkflowListing} from '../src/workflow/model';
import {seedWorkflow,previewUsers} from '../src/workflow/seed';
const context=(id:number)=>({actual:previewUsers[0],effective:previewUsers.find(u=>u.id===id)!});
let w=seedWorkflow()[0];
const act=(id:number,action:any)=>{w=applyWorkflowAction(w,action,context(id));};
act(2,{type:'handoff'});
act(3,{type:'addMaterial',kind:'photo',title:'Prepared photo',fileKey:'photo.png',mime:'image/png'});
act(3,{type:'addMaterial',kind:'copy',title:'Prepared copy',text:'Verified listing copy'});
act(3,{type:'addMaterial',kind:'video',title:'Pending video',fileKey:'video.mp4',mime:'video/mp4'});
const [photo,copy,video]=w.materials.map(m=>m.id);
act(3,{type:'submit',ids:[photo,copy,video]});
const channels=['facebook-page','telegram-subsale','whatsapp-nhc','tiktok'];
const selection={type:'approveForPublishing',channelIds:channels,materialIds:[photo,copy]};
assert.throws(()=>act(4,selection),/permission|publisher/i);
const version=w.version;
act(5,selection);
assert.equal(w.version,version+1,'One atomic handoff');
assert.equal(workflowStage(w),'Publishing');
assert.equal(w.destinations.filter(d=>d.approval).length,3,'Photo and copy packages go to selected destinations');
assert.equal(w.destinations.find(d=>d.channelId==='tiktok')!.approval,null,'Video platform remains pending until video is selected');
assert.deepEqual(w.materials.map(m=>m.review),['approved','approved','approved'],'Submitted materials are released automatically');
assert.equal(w.events[0].effectiveName,'Muz');
assert.match(w.events[0].message,/Muz selected/);
assert.match(ownerReport(w),/TikTok : Pending materials/);
assert.match(ownerReport(w),/Mudah : N\/A/);
assert.throws(()=>act(5,selection),/ready|already/i,'Retry cannot duplicate existing packages');
const originalApproval=w.destinations[0].approval!.id;
act(5,{type:'publish',channelId:'facebook-page',url:'https://example.com/published'});
const originalPublication=currentPublication(w.destinations[0])!.id;
act(5,{type:'setDestinations',channelIds:['facebook-page','whatsapp-nhc','tiktok']});
assert.equal(w.destinations.some(d=>d.channelId==='telegram-subsale'),false,'Unticked unpublished destination is removed');
assert.throws(()=>act(5,{type:'setDestinations',channelIds:['tiktok']}),/published|history/i);
act(5,{type:'approveForPublishing',channelIds:['facebook-page','whatsapp-nhc','tiktok'],materialIds:[photo,copy,video]});
assert.equal(w.destinations[0].approval!.id,originalApproval,'Adding video preserves existing platform package');
assert.equal(currentPublication(w.destinations[0])!.id,originalPublication,'Published Facebook link stays complete');
assert.deepEqual(w.destinations.find(d=>d.channelId==='tiktok')!.approval!.materialIds,[copy,video]);
const before=structuredClone(w);
function rejected(action:any,pattern:RegExp){assert.throws(()=>applyWorkflowAction(w,action,context(5)),pattern);assert.deepEqual(w,before);}
rejected({type:'setDestinations',channelIds:['facebook-page','unknown']},/channel|destination/i);
rejected({type:'setDestinations',channelIds:['facebook-page','facebook-page']},/unique|duplicate/i);
rejected({type:'approveForPublishing',channelIds:['facebook-page','mudah'],materialIds:['bad-id']},/material/i);
const blocked:WorkflowListing={...w,brief:{...w.brief,tasks:[{id:'price',label:'Confirm price',done:false}]}};
assert.throws(()=>applyWorkflowAction(blocked,{type:'approveForPublishing',channelIds:[...channels,'mudah'],materialIds:[photo,copy]} as any,context(5)),/checks/i);
const withdrawn={...w,brief:{...w.brief,permission:false}};
assert.throws(()=>applyWorkflowAction(withdrawn,selection as any,context(5)),/permission/i);
console.log('PASS atomic platform selection, direct publishing handoff, partial material readiness, permissions and history preservation');
